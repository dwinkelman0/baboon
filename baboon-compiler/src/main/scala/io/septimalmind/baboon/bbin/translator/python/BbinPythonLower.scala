package io.septimalmind.baboon.bbin.translator.python

import io.septimalmind.baboon.bbin.model._
import io.septimalmind.baboon.bbin.typer._

/** `.bbin` → Python lowering: runtime + core subset + input pipeline.
  *
  * Consumes the backend-neutral [[IRProgram]] (phase 6, see
  * `plans/inputs-ir.md`) and emits one Python module calling into
  * `baboon_runtime_bbin` (`IndexedSet` construction for `Lit` sets,
  * `csv_loader`/`json_loader` RUN-time calls for `LoaderRef` sets,
  * `bbin_filter` with real per-row predicates, slot-dict partials,
  * `bbin_assign_broadcast`, `for` loops, `with_provenance` blocks,
  * `leaf()`, `seal_row`).
  *
  * Loader detail (`csv` vs `json`, `.map` pairs, chain `.filter`) is not
  * in [[IROp]] (it records only `LoaderRef(source)` / `Filter(of)`), so
  * the `:inputs` CLI threads the raw RHS exprs through
  * [[lower(IRProgram,Map,String)]]; plain [[lower(IRProgram)]] keeps the
  * historical clean `NotImplementedError` naming the op.
  *
  * Set combinators (`Cross`/`Zip`/`Concat`/`Reindex`/joins) and
  * non-predicate filter constructs have no lowering: they emit a clean
  * `NotImplementedError` naming the op instead of failing silently. The
  * existing [[io.septimalmind.baboon.bbin.translator.BbinLowering]]
  * stub is untouched.
  */
object BbinPythonLower {

  /** Lower a whole program to one Python module source. */
  def lower(program: IRProgram): String =
    lower(program, Map.empty, "")

  /** Lower with input-pipeline context: `loaderExprs` maps set names to
    * their raw RHS (recovering loader kind/maps and filter predicates
    * that [[IROp]] drops), `sourceDir` is baked into `_BBIN_DIR` so
    * `rel:` targets resolve against the source `.bbin` directory. */
  def lower(program: IRProgram, loaderExprs: Map[String, BbinExpr], sourceDir: String = ""): String = {
    val out = new Emitter(program, loaderExprs, loaderExprs.keys.toList, sourceDir)
    out.emitProgram()
    out.result()
  }

  /** Lower with statement-ordered top-level `let` bindings: in addition to
    * the `loaderExprs` context above, scalar (non-set) `let`s are bound in
    * `main()` in source order between the set builds and the statements,
    * so broadcasts/seals/for loops see every binding. Seal/Unseal chain
    * suffixes are stripped here (the [[IRSeal]]/[[IRUnseal]] statements own
    * that step); anything else renders as-is. */
  def lowerOrdered(
    program: IRProgram,
    topLets: List[(String, BbinExpr)],
    sourceDir: String,
  ): String = {
    val out = new Emitter(program, topLets.toMap, topLets.map(_._1), sourceDir)
    out.emitProgram()
    out.result()
  }

  private final class Emitter(
    program: IRProgram,
    loaderExprs: Map[String, BbinExpr],
    letOrder: List[String],
    sourceDir: String,
  ) {
    private val sb     = new StringBuilder
    private var indent = 0

    def result(): String = sb.toString()

    private def line(s: String): Unit = {
      sb.append("  " * indent).append(s).append("\n")
    }

    private def blank(): Unit = sb.append("\n")

    def emitProgram(): Unit = {
      line("# Generated by BbinPythonLower: `.bbin` -> Python (runtime + input pipeline).")
      line("# Backend-neutral IR, see plans/inputs-ir.md phase 6; seal version = header `using` pin.")
      line("# Sealed rows print below as plain JSON dicts: no pygen dependency yet, so `seal_row`")
      line("# returns the validated slot map (constructor wiring deferred).")
      line("# Runtime helpers come from `baboon_runtime_bbin` (must be importable); `rel:` loader")
      line("# targets resolve against _BBIN_DIR (the source `.bbin` directory).")
      line("import copy")
      line("import json")
      line("")
      line("from baboon_runtime_bbin import (")
      indent += 1
      line("BbinSealError,")
      line("IndexedSet,")
      line("bbin_assign_broadcast,")
      line("bbin_filter,")
      line("csv_loader,")
      line("json_loader,")
      line("leaf,")
      line("seal_row,")
      line("with_provenance,")
      indent -= 1
      line(")")
      blank()
      line(s"_BBIN_DIR = ${quote(sourceDir)}")
      blank()
      line("def _bbin_unsupported(op):")
      indent += 1
      line("\"\"\"Clean failure for IR ops with no Python lowering yet.\"\"\"")
      line("raise NotImplementedError(f\".bbin op not yet lowered to Python: {op}\")")
      indent -= 1
      blank()
      program.rows.foreach(emitRowTemplate)
      if (program.rows.nonEmpty) blank()
      line("def main():")
      indent += 1
      line("\"\"\"Build every set, run every statement, then print sealed rows as JSON.\"\"\"")
      program.sets.foreach(emitSet)
      if (program.sets.nonEmpty) blank()
      val scalarLines = scalarBindings()
      scalarLines.foreach(line)
      if (scalarLines.nonEmpty) blank()
      if (program.stmts.isEmpty && program.sets.isEmpty && scalarLines.isEmpty) {
        line("pass")
      } else {
        program.stmts.foreach(emitStmt)
      }
      emitSealedPrint()
      indent -= 1
      blank()
      line("if __name__ == \"__main__\":")
      indent += 1
      line("main()")
      indent -= 1
    }

    /** End of `main`: dump every `IRSeal` target (plain JSON dicts, see the
      * header note) under its binding name. */
    private def emitSealedPrint(): Unit = {
      val targets = sealTargets(program.stmts).distinct
      blank()
      if (targets.isEmpty) {
        line("print(json.dumps({}))")
      } else {
        val entries = targets.map(t => s"${quote(t)}: ${pyIdent(t)}").mkString(", ")
        line(s"print(json.dumps({$entries}, default=str))")
      }
    }

    private def sealTargets(stmts: List[IRStmt]): List[String] = stmts.flatMap {
      case IRSeal(t, _)            => List(t)
      case IRFor(_, _, _, _, _, b) => sealTargets(b)
      case IRWithProv(_, b)        => sealTargets(b)
      case _                       => Nil
    }

    /** Slot-dict partial template: `None` marks an unfilled slot for `seal_row`. */
    private def emitRowTemplate(row: IRRow): Unit = {
      line(s"def __new_${pyIdent(row.name)}():")
      indent += 1
      line(s"\"\"\"IRRow ${row.name}: flat slot map (dot paths); provenance per slot in comments.\"\"\"")
      if (row.slots.isEmpty) {
        line("return {}")
      } else {
        line("return {")
        indent += 1
        row.slots.foreach { slot =>
          val prov = slot.provenance.map(p => s"  # provenance: $p").getOrElse("")
          line(s"${quote(slot.path)}: None,$prov")
        }
        indent -= 1
        line("}")
      }
      indent -= 1
      blank()
    }

    private def rowTemplateFor(rowName: String): String =
      if (program.rows.exists(_.name == rowName)) s"__new_${pyIdent(rowName)}()"
      else "{}"

    /** Scalar (non-set) top-level `let` bindings in source order: sets are
      * already built above, statements below consume these. Seal/Unseal
      * chain suffixes are stripped (the IRSeal/IRUnseal statements own that
      * step); anything unrenderable stays a `_bbin_unsupported(...)` call so
      * it fails at RUN time naming the op, never as invalid syntax. */
    private def scalarBindings(): List[String] = {
      val setNames = program.sets.map(_.name).toSet
      letOrder.flatMap { name =>
        if (setNames.contains(name)) None
        else
          loaderExprs.get(name).map { rhs =>
            val stripped = rhs match {
              case BbinExpr.Chain(base, ops) =>
                val kept = ops.filter(o => o != BbinChainOp.Seal && o != BbinChainOp.Unseal)
                if (kept.isEmpty) base else BbinExpr.Chain(base, kept)
              case other => other
            }
            s"${pyIdent(name)} = ${renderExpr(stripped)}  # IRLet $name"
          }
      }
    }

    private def emitSet(set: IRSet): Unit = {
      val comment = s"# IRSet ${set.name}${set.idx.map { case (i, t) => s" ($i: $t)" }.getOrElse("")}" +
        s" row=${set.row} partial=${set.partial} op=${renderOp(set.op)}"
      set.op match {
        case IROp.Lit(n) =>
          // Inline `{...}` literals keep their field values only in the raw
          // RHS (`IROp` records just the count): fill rows from it when the
          // shapes agree. Without raw context (plain `lower`) keep the empty
          // row templates so the gap stays explicit.
          val litRows: Option[List[String]] = loaderExprs.get(set.name).collect {
            case BbinExpr.SetLit(bset) if bset.entries.size == n =>
              bset.entries.map(e => renderStructLit(e.row, withComment = false))
          }
          val rowAt: Int => String = i =>
            litRows.map(_(i)).getOrElse(rowTemplateFor(set.row))
          set.idx match {
            case Some((idxName, _)) =>
              line(s"${pyIdent(set.name)} = IndexedSet({")
              indent += 1
              (0 until n).foreach { i =>
                line(s"$i: ${rowAt(i)},")
              }
              indent -= 1
              line(s"}, idx_tag=${quote(idxName)})  $comment")
            case None =>
              if (n == 0) {
                line(s"${pyIdent(set.name)} = []  $comment")
              } else {
                line(s"${pyIdent(set.name)} = [")
                indent += 1
                (0 until n).foreach { i => line(s"${rowAt(i)},") }
                indent -= 1
                line(s"]  $comment")
              }
          }
        case IROp.LoaderRef(_) =>
          emitLoaderSet(set, comment)
        case IROp.Filter(of) =>
          emitFilterSet(set, of, comment)
        case other =>
          line(s"${pyIdent(set.name)} = _bbin_unsupported(${quote(describeOp(other))})  $comment")
      }
    }

    /** RUN-time loader call: `(call, extraMaps, filter, rest)` comes from the
      * raw RHS (see `findLoader`) because [[IROp]] keeps only the source.
      * Leftover chain combinators fail cleanly naming the op; without loader
      * context (plain `lower(program)`) this stays the historical
      * `LoaderRef` `NotImplementedError`. */
    private def emitLoaderSet(set: IRSet, comment: String): Unit = {
      loaderExprs.get(set.name).flatMap(findLoader) match {
        case None =>
          line(s"${pyIdent(set.name)} = _bbin_unsupported(${quote(describeOp(set.op))})  $comment")
        case Some(info) =>
          if (info.restOps.nonEmpty) {
            val ops = info.restOps.map(describeChainOp).mkString(", ")
            line("raise NotImplementedError(" + quote(".bbin LoaderRef(" + info.call.source + ") chain op not yet lowered to Python: " + ops) + ")  " + comment)
          } else {
            val fn = info.call.kind match {
              case BbinLoaderKind.Csv  => "csv_loader"
              case BbinLoaderKind.Json => "json_loader"
            }
            val pairs = info.call.maps.flatMap(_.args.grouped(2).toList) ++
              info.extraMaps.flatMap(_.args.grouped(2).toList)
            renderMaps(pairs) match {
              case Left(err) =>
                line("raise NotImplementedError(" + quote(".bbin LoaderRef(" + info.call.source + ") " + err) + ")  " + comment)
              case Right(mapsPy) =>
                val base = s"$fn(${quote(info.call.source)}, None, $mapsPy, base_dir=_BBIN_DIR)"
                info.filterPred match {
                  case None =>
                    line(s"${pyIdent(set.name)} = $base  $comment")
                  case Some(pred) =>
                    renderPred(pred) match {
                      case Some(body) =>
                        line(s"${pyIdent(set.name)} = bbin_filter($base, lambda __row: $body)  $comment")
                      case None =>
                        line("raise NotImplementedError(" + quote(".bbin Filter predicate uses unsupported construct: " + describeExpr(pred)) + ")  " + comment)
                    }
                }
            }
          }
      }
    }

    /** `Filter(of)` set derivation: the predicate lives only in the raw RHS
      * chain, so without loader context this stays the historical
      * `Filter(of)` `NotImplementedError`. */
    private def emitFilterSet(set: IRSet, of: String, comment: String): Unit = {
      val pred = loaderExprs.get(set.name).collect {
        case c: BbinExpr.Chain => c.ops.collect { case BbinChainOp.Filter(p) => p }.lastOption
      }.flatten
      pred match {
        case Some(p) =>
          renderPred(p) match {
            case Some(body) =>
              line(s"${pyIdent(set.name)} = bbin_filter(${pyIdent(of)}, lambda __row: $body)  $comment")
            case None =>
              line("raise NotImplementedError(" + quote(".bbin Filter predicate uses unsupported construct: " + describeExpr(p)) + ")  " + comment)
          }
        case None =>
          line(s"${pyIdent(set.name)} = _bbin_unsupported(${quote(describeOp(set.op))})  $comment")
      }
    }

    /** Loader detail recovered from the raw RHS: the `Loader` call, extra
      * chain-level `.map(...)`s, the last chain-level `.filter(...)`
      * predicate, and leftover chain ops (combinators stay unsupported). */
    private final case class LoaderInfo(
      call: BbinLoaderCall,
      extraMaps: List[BbinMapCall],
      filterPred: Option[BbinExpr],
      restOps: List[BbinChainOp],
    )

    private def findLoader(expr: BbinExpr): Option[LoaderInfo] = expr match {
      case BbinExpr.Loader(call) =>
        Some(LoaderInfo(call, Nil, None, Nil))
      case BbinExpr.Chain(base, ops) =>
        base match {
          case BbinExpr.Loader(call) =>
            val maps    = ops.collect { case m: BbinChainOp.Map => BbinMapCall(m.args) }
            val filters = ops.collect { case BbinChainOp.Filter(p) => p }
            val rest    = ops.filter(o => !o.isInstanceOf[BbinChainOp.Map] && !o.isInstanceOf[BbinChainOp.Filter])
            Some(LoaderInfo(call, maps, filters.lastOption, rest))
          case _ => None
        }
      case _ => None
    }

    /** `.map(slot, .column)` pairs render as `(slot, [colpath])` for
      * `csv_loader`/`json_loader`; anything else names the gap. */
    private def renderMaps(pairs: List[List[BbinMapArg]]): Either[String, String] = {
      val rendered = pairs.map {
        case List(BbinMapArg.Str(slot), BbinMapArg.Path(segs)) =>
          Right(s"(${quote(slot)}, ${renderSegList(segs)})")
        case other =>
          Left(s"map entry not yet lowered to Python: ${other.map(describeMapArg).mkString(", ")}")
      }
      val errors = rendered.collect { case Left(e) => e }
      if (errors.nonEmpty) Left(errors.mkString("; "))
      else Right(s"[${rendered.collect { case Right(s) => s }.mkString(", ")}]")
    }

    private def renderSegList(segs: List[BbinPathSeg]): String =
      "[" + segs.map {
        case BbinPathSeg.Field(n) => quote(n)
        case BbinPathSeg.Index(i) => i.toString
      }.mkString(", ") + "]"

    private def describeMapArg(arg: BbinMapArg): String = arg match {
      case BbinMapArg.Str(v)   => s"Str($v)"
      case BbinMapArg.Path(s)  => s"Path(${renderSegs(s)})"
    }

    private def emitStmt(stmt: IRStmt): Unit = stmt match {
      case IRAssign(target, _, op, value) =>
        val (root, rest) = splitPath(target)
        val expr         = renderIExpr(value)
        if (rest.isEmpty) {
          line(s"${pyIdent(root)} = $expr  # IRAssign whole-row overwrite")
        } else {
          line(s"bbin_assign_broadcast(${pyIdent(root)}, ${quote(rest.mkString("."))}, $expr, ${quote(renderAssignOp(op))})")
        }
      case IRFor(idx, _, row, _, set, body) =>
        line(s"for ${pyIdent(idx)}, ${pyIdent(row)} in (${renderForSet(set)}):")
        indent += 1
        if (body.isEmpty) line("pass")
        else body.foreach(emitStmt)
        indent -= 1
      case IRWithProv(provenance, body) =>
        line(s"with with_provenance(${renderFields(provenance)}):  # IRWithProv")
        indent += 1
        if (body.isEmpty) line("pass")
        else body.foreach(emitStmt)
        indent -= 1
      case IRSeal(target, sealedType) =>
        line(s"${pyIdent(target)} = seal_row(${pyIdent(target)}, ${quote(sealedType)})  # IRSeal -> $sealedType")
      case IRUnseal(target, _) =>
        line(s"${pyIdent(target)} = copy.deepcopy(${pyIdent(target)})  # IRUnseal: unseal by copy")
      case IRLeaf(base, overrides) =>
        val ov = overrides.map(quote).mkString(", ")
        if (base == "<expr>") {
          line(s"raise NotImplementedError(${quote(".bbin Leaf on a non-binding base (IRLeaf overrides: [" + ov + "])")})")
        } else
          loaderExprs.get(base) match {
            case Some(_: BbinExpr.Leaf) =>
              line(s"pass  # IRLeaf $base already built by its IRLet leaf(...) binding (overrides: [$ov])")
            case _ =>
              line(s"${pyIdent(base)} = leaf(${pyIdent(base)})  # IRLeaf overrides: [$ov]")
          }
      case IRJoin(kind, left, right) =>
        line(s"raise NotImplementedError(${quote(s".bbin Join(kind=$kind, left=$left, right=$right) not yet lowered to Python")})")
    }

    private def renderForSet(set: IRExpr): String = set.expr match {
      case BbinExpr.Ident(name) => s"${pyIdent(name)}.items() if isinstance(${pyIdent(name)}, IndexedSet) else enumerate(${pyIdent(name)})"
      case other                => s"_bbin_unsupported(${quote("ForSet(" + renderExpr(other) + ")")})"
    }

    private def renderIExpr(expr: IRExpr): String = renderExpr(expr.expr)

    private def renderExpr(expr: BbinExpr): String = expr match {
      case BbinExpr.StrLit(v)          => quote(v)
      case BbinExpr.IntLit(_, raw)     => raw
      case BbinExpr.FloatLit(_, raw)   => raw
      case BbinExpr.BoolLit(v)         => if (v) "True" else "False"
      case BbinExpr.NoneLit            => "None"
      case BbinExpr.UndefinedLit       => "None  # undefined (deletes the slot in partial position)"
      case BbinExpr.Ident(n)           => pyIdent(n)
      case BbinExpr.Rel(path)          => quote(path)
      case BbinExpr.SchemaPath(path)   => s"${quote(renderPath(path))}  # deferred SchemaPath: per-row value"
      case BbinExpr.BinOp(op, l, r)    => s"(${renderExpr(l)} ${renderBinOp(op)} ${renderExpr(r)})"
      case BbinExpr.Leaf(base, over)   => s"leaf(${renderExpr(base)}, ${renderFields(over)})"
      case BbinExpr.StructLit(row)     => renderStructLit(row)
      case BbinExpr.PartialSeal(t)     => t.map(e => s"seal_row(${renderExpr(e)})").getOrElse("{}")
      case BbinExpr.Loader(call)       => "_bbin_unsupported(" + quote("LoaderRef(" + call.source + ")") + ")"
      case BbinExpr.SetLit(set)        => renderSetLit(set)
      case c: BbinExpr.Chain           => renderChain(c)
    }

    private def renderChain(chain: BbinExpr.Chain): String = {
      val base = renderExpr(chain.base)
      chain.ops match {
        case List(BbinChainOp.Seal)   => s"seal_row($base)"
        case List(BbinChainOp.Unseal) => s"copy.deepcopy($base)"
        case List(BbinChainOp.Filter(pred)) =>
          renderPred(pred) match {
            case Some(body) => s"bbin_filter($base, lambda __row: $body)"
            case None        => "_bbin_unsupported(" + quote("Filter(" + describeExpr(pred) + ")") + ")"
          }
        case ops if ops.contains(BbinChainOp.Seal) =>
          s"seal_row($base)  # chain with Seal + ${ops.size - 1} more op(s)"
        case ops =>
          s"_bbin_unsupported(${quote("Chain(" + ops.map(describeChainOp).mkString(", ") + ")")})"
      }
    }

    /** Real `Filter` predicates over `==,!=,<,<=,>,>=,+,-,*,/` on paths and
      * literals lower to a `__row`-dict lambda body; anything else is
      * `None` so callers raise `NotImplementedError` naming the construct. */
    private def renderPred(expr: BbinExpr): Option[String] = expr match {
      case BbinExpr.SchemaPath(path) => Some(renderRowLookup(path))
      case BbinExpr.Ident(n)          => Some(pyIdent(n))
      case BbinExpr.StrLit(v)         => Some(quote(v))
      case BbinExpr.IntLit(_, raw)    => Some(raw)
      case BbinExpr.FloatLit(_, raw)  => Some(raw)
      case BbinExpr.BoolLit(v)        => Some(if (v) "True" else "False")
      case BbinExpr.NoneLit           => Some("None")
      case BbinExpr.BinOp(op, l, r) if isPredOp(op) =>
        for {
          ls <- renderPred(l)
          rs <- renderPred(r)
        } yield s"($ls ${renderBinOp(op)} $rs)"
      case _ => None
    }

    private def isPredOp(op: BbinBinOp): Boolean = op match {
      case BbinBinOp.Eq | BbinBinOp.Ne | BbinBinOp.Lt | BbinBinOp.Le |
          BbinBinOp.Gt | BbinBinOp.Ge | BbinBinOp.Add | BbinBinOp.Sub |
          BbinBinOp.Mul | BbinBinOp.Div =>
        true
    }

    /** `__row["a"]["b"][0]`: per-row slot lookup for a schema path. */
    private def renderRowLookup(path: BbinPath): String =
      path.segments.foldLeft("__row") {
        case (acc, BbinPathSeg.Field(n)) => s"$acc[${quote(n)}]"
        case (acc, BbinPathSeg.Index(i)) => s"$acc[$i]"
      }

    /** Short construct name for `NotImplementedError` messages. */
    private def describeExpr(expr: BbinExpr): String = expr match {
      case BbinExpr.SetLit(_)        => "SetLit"
      case BbinExpr.Loader(call)     => s"LoaderRef(${call.source})"
      case BbinExpr.Rel(p)           => s"Rel($p)"
      case BbinExpr.SchemaPath(p)    => s"SchemaPath(${renderPath(p)})"
      case BbinExpr.Ident(n)         => s"Ident($n)"
      case BbinExpr.StrLit(v)        => s"StrLit($v)"
      case BbinExpr.IntLit(_, r)     => s"IntLit($r)"
      case BbinExpr.FloatLit(_, r)   => s"FloatLit($r)"
      case BbinExpr.BoolLit(v)       => s"BoolLit($v)"
      case BbinExpr.NoneLit          => "NoneLit"
      case BbinExpr.UndefinedLit     => "UndefinedLit"
      case BbinExpr.BinOp(op, _, _)  => s"BinOp(${renderBinOp(op)})"
      case BbinExpr.Leaf(_, _)       => "Leaf"
      case BbinExpr.StructLit(row)   => s"StructLit(${row.typeName.name})"
      case BbinExpr.PartialSeal(_)   => "PartialSeal"
      case c: BbinExpr.Chain         => s"Chain(${c.ops.map(describeChainOp).mkString(", ")})"
    }

    private def renderSetLit(set: BbinSet): String = {
      if (set.entries.isEmpty) return "[]"
      val entries = set.entries.map { e =>
        val key = e.key.map(k => s"$k: ").getOrElse("")
        // No per-entry `# Type` comment: inside a list literal it would
        // comment out the separators/closing bracket.
        s"$key${renderStructLit(e.row, withComment = false)}"
      }
      s"[${entries.mkString(", ")}]"
    }

    private def renderStructLit(row: BbinRow, withComment: Boolean = true): String = {
      val fields = row.fields.map(f => s"${quote(f.name)}: ${renderFieldValue(f.value)}")
      val dict   = s"{${fields.mkString(", ")}}"
      if (withComment) s"$dict  # ${row.typeName.name}" else dict
    }

    private def renderFields(fields: List[BbinField]): String = {
      val parts = fields.map(f => s"${quote(f.name)}: ${renderFieldValue(f.value)}")
      s"{${parts.mkString(", ")}}"
    }

    private def renderFieldValue(value: BbinFieldValue): String = value match {
      case BbinFieldValue.Str(v)       => quote(v)
      case BbinFieldValue.Int(_, raw)  => raw
      case BbinFieldValue.Float(_, raw) => raw
      case BbinFieldValue.Bool(v)      => if (v) "True" else "False"
      case BbinFieldValue.NoneLit      => "None"
      case BbinFieldValue.Undefined    => "None  # undefined"
      case BbinFieldValue.Path(segs)   => quote(renderSegs(segs))
      case BbinFieldValue.Rel(path)    => quote(path)
      case BbinFieldValue.Ident(name)  => pyIdent(name)
    }

    private def splitPath(path: BbinPath): (String, List[String]) = {
      val parts = path.segments.map {
        case BbinPathSeg.Field(n) => n
        case BbinPathSeg.Index(i) => s"[$i]"
      }
      (parts.headOption.getOrElse("<expr>"), parts.drop(1))
    }

    private def renderPath(path: BbinPath): String =
      path.segments.map {
        case BbinPathSeg.Field(n) => n
        case BbinPathSeg.Index(i) => s"[$i]"
      }.mkString(".")

    private def renderSegs(segs: List[BbinPathSeg]): String =
      segs.map {
        case BbinPathSeg.Field(n) => n
        case BbinPathSeg.Index(i) => s"[$i]"
      }.mkString(".")

    private def renderAssignOp(op: BbinAssignOp): String = op match {
      case BbinAssignOp.Set => "set"
      case BbinAssignOp.Add => "add"
      case BbinAssignOp.Mul => "mul"
    }

    private def renderBinOp(op: BbinBinOp): String = op match {
      case BbinBinOp.Eq  => "=="
      case BbinBinOp.Ne  => "!="
      case BbinBinOp.Lt  => "<"
      case BbinBinOp.Le  => "<="
      case BbinBinOp.Gt  => ">"
      case BbinBinOp.Ge  => ">="
      case BbinBinOp.Add => "+"
      case BbinBinOp.Sub => "-"
      case BbinBinOp.Mul => "*"
      case BbinBinOp.Div => "/"
    }

    private def renderOp(op: IROp): String = op match {
      case IROp.Lit(n)       => s"Lit($n)"
      case IROp.LoaderRef(s) => s"LoaderRef($s)"
      case other             => describeOp(other)
    }

    private def describeOp(op: IROp): String = op match {
      case IROp.Lit(n)       => s"Lit($n)"
      case IROp.LoaderRef(s) => s"LoaderRef($s)"
      case IROp.Cross(of)    => s"Cross(of=$of)"
      case IROp.Zip(of)      => s"Zip(of=$of)"
      case IROp.Concat(of)   => s"Concat(of=$of)"
      case IROp.Join(of)     => s"Join(of=$of)"
      case IROp.Reindex(of)  => s"Reindex(of=$of)"
      case IROp.Filter(of)   => s"Filter(of=$of)"
    }

    private def describeChainOp(op: BbinChainOp): String = op match {
      case BbinChainOp.Map(_)            => "Map"
      case BbinChainOp.Filter(_)         => "Filter"
      case BbinChainOp.Cross(o)          => s"Cross(${renderExpr(o)})"
      case BbinChainOp.InnerJoin(o)      => s"InnerJoin(${renderExpr(o)})"
      case BbinChainOp.OuterJoin(o)      => s"OuterJoin(${renderExpr(o)})"
      case BbinChainOp.LeftJoin(o)       => s"LeftJoin(${renderExpr(o)})"
      case BbinChainOp.RightJoin(o)      => s"RightJoin(${renderExpr(o)})"
      case BbinChainOp.Zip(o)            => s"Zip(${renderExpr(o)})"
      case BbinChainOp.Concat(o)         => s"Concat(${renderExpr(o)})"
      case BbinChainOp.Reindex(o)        => s"Reindex(${renderExpr(o)})"
      case BbinChainOp.Seal              => "Seal"
      case BbinChainOp.Unseal            => "Unseal"
      case BbinChainOp.WithProvenance(_) => "WithProvenance"
      case BbinChainOp.Unwrap            => "Unwrap"
    }

    private def quote(s: String): String =
      "\"" + s.flatMap {
        case '"'  => "\\\""
        case '\\' => "\\\\"
        case '\n' => "\\n"
        case c    => c.toString
      } + "\""

    private def pyIdent(name: String): String = name
  }
