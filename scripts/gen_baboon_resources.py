#!/usr/bin/env python3
"""Bazel replacement for izumi PortableResource.embedSources (compile-time macro).

Reads every file under baboon-compiler/src/main/resources/baboon-runtime/**
and emits a Scala source defining the same object the macro used to generate:

  package io.septimalmind.baboon.translator
  object BaboonRuntimeResources {
    private val resources: Map[String, String] = ...
    def read(path: String): String = ...
  }

Map keys are paths relative to src/main/resources (e.g.
"baboon-runtime/scala/BaboonFixtureShared.scala"), identical to the macro's
keys (glob basePath stripped). Values are split into <=20000-char chunks,
mirroring PortableResourceBase.chunkString, so no string literal exceeds the
JVM 65535-byte CONSTANT_Utf8 limit.

Unlike the macro (which requires build.sbt at the workspace root and fails
under Bazel workers/sandboxes), this reruns automatically whenever any
template file changes.
"""

import argparse
import sys


MAX_CHUNK_CHARS = 20000
MARKER = "baboon-runtime/"


def scala_escape(chunk: str) -> str:
    out = []
    for ch in chunk:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == '\\':
            out.append('\\\\')
        elif ch == '\n':
            out.append('\\n')
        elif ch == '\r':
            out.append('\\r')
        elif ch == '\t':
            out.append('\\t')
        elif o < 0x20:
            out.append('\\u%04x' % o)
        else:
            out.append(ch)
    return ''.join(out)


def key_for(path: str) -> str:
    idx = path.replace('\\', '/').find(MARKER)
    if idx < 0:
        raise ValueError('resource path does not contain %r: %s' % (MARKER, path))
    return path.replace('\\', '/')[idx:]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', required=True)
    ap.add_argument('files', nargs='+')
    args = ap.parse_args()

    entries = {}
    for path in sorted(args.files):
        key = key_for(path)
        with open(path, 'r', encoding='utf-8') as f:
            content = f.read()
        chunks = [content[i:i + MAX_CHUNK_CHARS] for i in range(0, max(len(content), 1), MAX_CHUNK_CHARS)]
        entries[key] = chunks

    with open(args.out, 'w', encoding='utf-8') as out:
        out.write('package io.septimalmind.baboon.translator\n')
        out.write('\n')
        out.write('// GENERATED by //scripts:gen_baboon_resources from\n')
        out.write('// baboon-compiler/src/main/resources/baboon-runtime/** -- do not edit.\n')
        out.write('object BaboonRuntimeResources {\n')
        out.write('  private val resources: Map[String, String] = Map(\n')
        items = sorted(entries.items())
        for i, (key, chunks) in enumerate(items):
            comma = ',' if i < len(items) - 1 else ''
            if len(chunks) == 1:
                out.write('    "%s" -> "%s"%s\n' % (scala_escape(key), scala_escape(chunks[0]), comma))
            else:
                seq = ', '.join('"%s"' % scala_escape(c) for c in chunks)
                out.write('    "%s" -> Seq(%s).mkString%s\n' % (scala_escape(key), seq, comma))
        out.write('  )\n')
        out.write('\n')
        out.write('  def read(path: String): String = {\n')
        out.write('    resources.getOrElse(path, throw new RuntimeException(s"Runtime resource not found: $path, available: ${resources.keys.mkString(", ")}"))\n')
        out.write('  }\n')
        out.write('}\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())
