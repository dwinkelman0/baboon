#!/usr/bin/env python3
"""Generate test/sw-stub/BUILD.bazel from Package.swift + a codegen tree.

Bazel cannot address subsets of a rule's outputs, and every Swift module
(lib + test) must compile exactly its own files (a single target would merge
30 modules and break `@testable import` plus hit SPM-style basename
collisions). So this script emits one baboon_codegen + one swift_library /
swift_test per Package.swift target, each declaring only its module's files.
Each codegen action runs the full compiler (~2s) and keeps its subset.

Usage:
  bazel run //baboon-compiler:baboon-bin -- <flags> --output /tmp/swgen/Sources ...
  python3 tools/bazel/gen_sw_build.py /tmp/swgen test/sw-stub/Package.swift test/sw-stub/BUILD.bazel

Check in the result; re-run when baboon-compiler/src/test/resources/baboon/**
or Package.swift targets change.
"""

import os
import re
import sys


def parse_package_swift(path):
    """Parse .target()/.testTarget() entries into (kind, name, path, deps)."""
    text = open(path).read()
    out = []
    # Match .target( ... ) / .testTarget( ... ) blocks (no nesting inside).
    for m in re.finditer(r"\.(target|testTarget)\(\s*(.*?)\s*\)", text, re.DOTALL):
        kind, body = m.group(1), m.group(2)
        name_m = re.search(r'name:\s*"([^"]+)"', body)
        if not name_m:
            continue
        name = name_m.group(1)
        if "<" in name or ">" in name:
            continue
        path_m = re.search(r'path:\s*"([^"]+)"', body)
        if not path_m:
            continue
        deps = re.findall(r'"([A-Za-z0-9_]+)"', re.search(r"dependencies:\s*\[(.*?)\]", body, re.DOTALL).group(1)) if "dependencies" in body else []
        out.append((kind, name, path_m.group(1), deps))
    return out


def swift_files(tree_root, rel_path):
    """List .swift files under tree_root/rel_path, sorted, or []."""
    d = os.path.join(tree_root, rel_path)
    found = []
    for base, _dirs, files in os.walk(d):
        for f in sorted(files):
            if f.endswith(".swift"):
                full = os.path.join(base, f)
                found.append(os.path.relpath(full, tree_root).replace(os.sep, "/"))
    return sorted(found)


def main():
    tree_root, package_swift, out_path = sys.argv[1], sys.argv[2], sys.argv[3]
    targets = parse_package_swift(package_swift)
    lines = []
    A = lines.append
    A('load("@rules_swift//swift:swift.bzl", "swift_library", "swift_test")')
    A('load("//tools/bazel:baboon.bzl", "baboon_codegen")')
    A("")
    A('package(default_visibility = ["//visibility:public"])')
    A("")
    A("# GENERATED by tools/bazel/gen_sw_build.py from Package.swift + a")
    A("# `baboon --model-dir ... :swift` codegen tree. DO NOT EDIT BY HAND;")
    A("# re-run the generator instead (see its docstring).")
    A("")
    A('_SW_FLAGS = [')
    A('    "--sw-write-evolution-dict=true",')
    A('    "--sw-wrapped-adt-branch-codecs=false",')
    A('    "--generate-ueba-codecs-by-default=true",')
    A('    "--generate-json-codecs-by-default=true",')
    A(']')
    A("")

    have_runtime_fixture = os.path.isfile(os.path.join(tree_root, "Tests/BaboonTests/CrossLanguageFixturePath.swift"))

    for kind, name, path, deps in targets:
        safe = re.sub(r"[^0-9A-Za-z_]", "_", name)
        rel = path  # e.g. Sources/MyOk or Tests/BaboonTests/MyOk
        files = swift_files(tree_root, rel)
        if not files:
            # No generated files here (e.g. hand-written-only dirs); emit a
            # glob-based target instead so hand-written sources still build.
            A("# %s %s: no generated files under %s; hand-written only." % (kind, name, rel))
            if kind == "testTarget":
                A("swift_test(")
            else:
                A("swift_library(")
            A('    name = "%s",' % name)
            A('    srcs = glob(["%s/**/*.swift"]),' % rel)
            if deps:
                A("    deps = [%s]," % ", ".join('":%s"' % d for d in deps))
            A(")")
            A("")
            continue
        # Codegen target declaring exactly this module's files.
        gen = "gen_" + safe
        A("baboon_codegen(")
        A('    name = "%s",' % gen)
        A('    compiler_jar = "//baboon-compiler:baboon-bin_deploy.jar",')
        A("    extra_args = _SW_FLAGS,")
        A('    fixture_output = "gensw/Sources",')
        A('    lang = ":swift",')
        A('    model_dir = "baboon-compiler/src/test/resources/baboon",')
        A('    models = "//baboon-compiler:codegen_models",')
        A('    outs = [')
        for f in files:
            A('        "gensw/%s",' % f)
        extra_outs = []
        copy_files = {}
        if kind == "testTarget" and have_runtime_fixture:
            # Each test module compiles its own copy of the top-level
            # cross-language fixture helper (same-module free functions).
            top = "gensw/Tests/BaboonTests/CrossLanguageFixturePath.swift"
            dest = "gensw/%s/CrossLanguageFixturePath.swift" % rel
            if top not in ["gensw/" + f for f in files]:
                extra_outs.append(top)
            extra_outs.append(dest)
            copy_files[dest] = top
        for f in extra_outs:
            A('        "%s",' % f)
        A("    ],")
        if copy_files:
            A("    copy_files = {")
            for dest, src in sorted(copy_files.items()):
                A('        "%s": "%s",' % (dest, src))
            A("    },")
        A('    output = "gensw/Sources",')
        A('    test_output = "gensw/Tests/BaboonTests",')
        A(")")
        A("")
        # Swift compile/test target over exactly those files.
        if kind == "testTarget":
            A("swift_test(")
        else:
            A("swift_library(")
        A('    name = "%s",' % name)
        A("    srcs = [")
        A('        ":%s",' % gen)
        A("    ],")
        if kind == "testTarget":
            # Cross-language fixture root override (mirrors the other lanes).
            A('    env = {"BABOON_CROSS_LANG_FIXTURE_ROOT": "."},')
        if deps:
            A("    deps = [%s]," % ", ".join('":%s"' % d for d in deps))
        A(")")
        A("")
    open(out_path, "w").write("\n".join(lines))
    print("wrote %s (%d targets)" % (out_path, len(targets)))


if __name__ == "__main__":
    sys.exit(main())
